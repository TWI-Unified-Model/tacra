package platform

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/x509"
	"errors"
	"fmt"
)

// Plugin is the TACRA Platform Plug-In. It runs inside the Attester TEE and
// is the only component that talks to the platform ABI (quote, RNG, keys).
type Plugin interface {
	// Name identifies the backend (for example "simulated").
	Name() string

	// GenerateCEK creates an asymmetric Credential Encryption Key used in
	// Retrieval mode. The public half is bound into Evidence; the private
	// half unwraps the credential the CAS returns.
	GenerateCEK() (*KeyPair, error)

	// GenerateCSK creates an asymmetric Credential Signing Key used in
	// Enrollment mode. The public half is bound into Evidence; the private
	// half signs the CSR.
	GenerateCSK() (*KeyPair, error)

	// GenerateEvidence produces RATS Evidence as a CBOR-encoded tagged
	// COSE_Sign1 EAT covering the verifier challenge and the bound key
	// (CEKpub or CSKpub). CSR, when present, is included as a profile
	// claim so Evidence and CSR are bound together.
	GenerateEvidence(req EvidenceRequest) (*Evidence, error)

	// AttestationPublicKey is the AK that signs Evidence. Provision it to
	// the Verifier as a CoRIM trust anchor.
	AttestationPublicKey() *ecdsa.PublicKey
}

// KeyPair is a P-256 key generated by the plug-in.
//
// CEK is used for ECDH wrapping; CSK is used as a crypto.Signer for CSRs.
// Both are P-256 so a single encoding path covers Retrieval and Enrollment.
type KeyPair struct {
	Private *ecdsa.PrivateKey
}

// Public returns the public half of the key pair.
func (k *KeyPair) Public() *ecdsa.PublicKey {
	if k == nil || k.Private == nil {
		return nil
	}
	return &k.Private.PublicKey
}

// PublicPKIX returns the PKIX/SPKI encoding of the public key.
func (k *KeyPair) PublicPKIX() ([]byte, error) {
	pub := k.Public()
	if pub == nil {
		return nil, errors.New("platform: nil key pair")
	}
	return x509.MarshalPKIXPublicKey(pub)
}

// PrivatePKCS8 returns the PKCS#8 encoding of the private key.
func (k *KeyPair) PrivatePKCS8() ([]byte, error) {
	if k == nil || k.Private == nil {
		return nil, errors.New("platform: nil key pair")
	}
	return x509.MarshalPKCS8PrivateKey(k.Private)
}

// Signer returns the private key as a crypto.Signer (for CSR generation).
func (k *KeyPair) Signer() (crypto.Signer, error) {
	if k == nil || k.Private == nil {
		return nil, errors.New("platform: nil key pair")
	}
	return k.Private, nil
}

// BoundKeyUse says whether the key confirmed in Evidence is a CEK or a CSK.
type BoundKeyUse int64

const (
	BoundKeyUseUnspecified BoundKeyUse = 0
	BoundKeyUseEncrypt     BoundKeyUse = 1 // CEK, Retrieval
	BoundKeyUseSign        BoundKeyUse = 2 // CSK, Enrollment
)

// EvidenceRequest is the input to Plugin.GenerateEvidence.
type EvidenceRequest struct {
	// Challenge is the Verifier nonce from Initiate-Credential-Acquisition.
	// RFC 9711 requires 8–64 bytes.
	Challenge []byte

	// BoundKey is CEKpub (Retrieval) or CSKpub (Enrollment). It is placed
	// in the EAT cnf claim so the Verifier can confirm possession.
	BoundKey crypto.PublicKey

	// CSR is the PKCS#10 request for Enrollment. Empty for Retrieval.
	CSR []byte

	// BoundKeyUse selects encrypt vs sign. If Unspecified, Enrollment is
	// inferred from a non-empty CSR and Retrieval otherwise.
	BoundKeyUse BoundKeyUse
}

// Evidence is RATS Evidence ready to send over CAAPI.
type Evidence struct {
	// Token is the CBOR-encoded tagged COSE_Sign1 EAT (CBOR tag 18).
	Token []byte

	// MediaType is the IANA type a Veraison-class verifier uses to dispatch
	// the token to an EAT/CWT scheme.
	MediaType string

	// Claims is the unsigned CBOR claims map (the COSE_Sign1 payload).
	Claims []byte
}

var (
	ErrInvalidChallenge = errors.New("platform: challenge must be 8-64 bytes")
	ErrMissingBoundKey  = errors.New("platform: bound public key is required")
	ErrUnsupportedKey   = errors.New("platform: bound key must be a P-256 ECDSA public key")
	ErrNilPlugin        = errors.New("platform: nil plugin")
)

func ecdsaP256Public(pub crypto.PublicKey) (*ecdsa.PublicKey, error) {
	if pub == nil {
		return nil, ErrMissingBoundKey
	}
	switch k := pub.(type) {
	case *ecdsa.PublicKey:
		if k.Curve != elliptic.P256() {
			return nil, fmt.Errorf("%w: curve %s", ErrUnsupportedKey, k.Curve.Params().Name)
		}
		return k, nil
	case ecdsa.PublicKey:
		return ecdsaP256Public(&k)
	default:
		return nil, fmt.Errorf("%w: %T", ErrUnsupportedKey, pub)
	}
}

func resolveKeyUse(req EvidenceRequest) BoundKeyUse {
	if req.BoundKeyUse != BoundKeyUseUnspecified {
		return req.BoundKeyUse
	}
	if len(req.CSR) > 0 {
		return BoundKeyUseSign
	}
	return BoundKeyUseEncrypt
}
